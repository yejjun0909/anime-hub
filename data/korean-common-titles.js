function malIdOf(media) {
  if (!media || typeof media !== 'object') return '';
  let value = media.idMal ?? media.mal_id ?? media.malId ?? media.mal;
  if (value == null) {
    const raw = String(media.id ?? media.media_id ?? '').trim().toLowerCase();
    if (raw.startsWith('mal:')) value = raw.slice(4);
  }
  const key = String(value ?? '').trim();
  return /^[1-9]\d*$/.test(key) ? key : '';
}

/** @returns {{title:string,source:string,url:string,kind:'common'}|null} */
export function lookupCommonKoreanTitle(media) {
  const key = malIdOf(media);
  if (!key) return null;
  const title = COMMON_KOREAN_TITLES[key];
  if (!title) return null;
  return { title, source: COMMON_TITLE_SOURCE, url: '', kind: 'common' };
}
